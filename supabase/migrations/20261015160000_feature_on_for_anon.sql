-- The health check is fetched with no session, so `anon` must be able to read a
-- switch. One grant.
--
-- Build it 29, and this is a fix-forward for a mistake in
-- 20261015120000_feature_switches.sql -- which is APPLIED TO PRODUCTION, so it
-- cannot be edited. That migration revoked EXECUTE on `public.feature_on(text)`
-- from `anon` by name, and `web/src/app/health/route.ts` then called it from a
-- route an uptime monitor fetches WITH NO SESSION. A caller with no session uses
-- the publishable key, which is the `anon` role.
--
-- SO /health HAS ANSWERED 503 `error` ON PRODUCTION SINCE THE MERGE OF PR #316,
-- and the cause was never a missing setting:
--
--   $ curl -i https://<production>/health
--   HTTP/1.1 503 Service Unavailable
--   error
--
-- Measured on a local PostgreSQL 17.10 sandbox with all nineteen migrations
-- applied (evidence/build-it-29-kill-switches.md, section 15):
--
--   anon           has_function_privilege = f   -> ERROR: permission denied for
--                                                  function feature_on
--   authenticated  has_function_privilege = t   -> t
--   service_role   has_function_privilege = t
--
-- AND THE ROUTE'S OWN COMMENT CLAIMED THE OPPOSITE, which is the part worth
-- recording rather than quietly fixing: it said the function "is granted to
-- `authenticated` AND to no client role beyond that -- so an anonymous caller here
-- reaches it through the publishable key the same way every signed-out screen
-- does." Those two halves contradict each other, and the sentence was written in
-- the same change as the revoke. That comment is corrected in this pull request.
--
-- ---------------------------------------------------------------------------
-- WHAT THIS WIDENS, STATED RATHER THAN IMPLIED
-- ---------------------------------------------------------------------------
--
-- A SIGNED-OUT CALLER CAN NOW LEARN WHETHER A FEATURE IS SWITCHED OFF. That is
-- the whole of it, and it is a fact about this app rather than about any person:
--
--   * the function takes no user id and cannot be asked about anybody. Whoever
--     asks, the answer is the same;
--   * it returns ONE BOOLEAN. No feature list, no timestamp, no reason, nothing
--     about who switched it or when;
--   * `public.feature_switches` ITSELF IS UNTOUCHED and stays unreachable by every
--     role -- `anon`, `authenticated` and `service_role` all hold no SELECT, no
--     INSERT, no UPDATE and no DELETE on it. Nobody gains the ability to read which
--     switches exist, to see `changed_at`, or to change anything;
--   * and the app tells people anyway: a switched-off feature's whole purpose is a
--     sentence on a screen saying so.
--
-- THE ALTERNATIVE WAS TO STOP /health TOUCHING THE DATABASE, and it is worse for
-- the reason that file argues at length: a health check that only proved Next.js
-- was running would answer `ok` through the whole of the failure that matters most
-- -- Vercel up, database gone, every screen broken.
--
-- EXPAND ONLY. One grant. No table, column, constraint, index, policy, trigger or
-- function is created, altered or dropped, and no other privilege changes.
--
-- DO NOT EDIT THIS FILE once it has been applied anywhere. On the day it was
-- written it had been applied NOWHERE: not local, not staging, not production.

-- `anon` BY NAME, and not to PUBLIC. A grant to PUBLIC would reach every role in
-- the database including ones Supabase adds later; this names the one role that
-- needs it. `service_role` and `authenticated` already hold it from the migration
-- above and are not mentioned here, so nothing about them can change by accident.
grant execute on function public.feature_on(text) to anon;

