-- Tasks: drop the three superseded owner-only rules.
--
-- Build it 15, part 3 of 4 (issue #90). THE CONTRACT STEP, AND THE DATABASE
-- ONLY. No app or UI code goes with this migration, on purpose: parts 1 and 2
-- are live, every screen already works against the member-level rules, and this
-- step removes rules that nothing reads any more.
--
-- Part 1 (20261002133637_tasks_join_teams.sql) was the EXPAND step: it added
-- member-level read, change and add rules ALONGSIDE the owner-only ones from
-- 20260927182443_create_tasks.sql, so that the database was correct for the code
-- before the change and for the code after it. Part 2 (PR #89) built the screens
-- that use them. Both are applied to staging and to production.
--
-- This file removes the scaffolding. It drops exactly the three policies the
-- expand migration's own closing comment names, and keeps the one it says to
-- keep. Nothing else changes: no new policy, no change to the trigger, no change
-- to any column, index or grant.
--
-- THE DROP LIST, QUOTED FROM 20261002133637_tasks_join_teams.sql, lines 402-424,
-- "What the contract step does, when it comes":
--
--     drop  "Owners can read their own tasks"        -- superset above
--     drop  "Owners can add tasks for themselves"    -- superset above, and the
--                                                       reason the trigger has to
--                                                       police insert today
--     drop  "Owners can change their own tasks"      -- superset above, and WIDER
--                                                       than it looks: its with
--                                                       check lets the creator
--                                                       file a task into a team
--                                                       they do not belong to
--     KEEP  "Owners can remove their own tasks"      -- this IS the delete rule for
--                                                       team tasks. Dropping it
--                                                       would leave tasks with no
--                                                       delete policy at all, and
--                                                       nobody could delete
--                                                       anything.
--
-- WHY DROP THEM RATHER THAN LEAVE THEM. Policies for the same command are OR-ed,
-- so a rule that allows nothing the surviving rules do not already allow changes
-- no answer -- it only adds a second expression to read before you know what the
-- table permits. 20261002122203_team_rules.sql made the same argument when it
-- replaced the owner-only reads on teams and team_members, and this is the same
-- move for tasks.
--
-- ONE THING TO HOLD ON TO WHILE READING THE THREE SECTIONS BELOW, because two of
-- them turn on it: tasks_enforce_column_rules is a BEFORE ROW trigger, and a
-- BEFORE ROW trigger runs before a policy's with check is evaluated. So wherever
-- the trigger and a with check would both refuse the same statement, the trigger
-- gets there first and its sentence is the error the caller sees. That is why
-- dropping a with check that was wider than the trigger changes no message and
-- no answer: the statements it used to wave through were being refused one step
-- earlier the whole time. It was checked rather than reasoned about -- see the
-- pull request for #90, which runs the same script against a database with this
-- migration and one without and diffs the two outputs.
--
-- WHAT A PERSON CAN DO AFTER THIS MIGRATION is what they could do before it, with
-- one exception, named in section 3 and nowhere else.
--
-- DO NOT EDIT THIS FILE once it has been applied anywhere. A migration is
-- applied once; editing an applied one leaves the repository and every database
-- that has already run it silently disagreeing, and the edit reaches none of
-- them. To change any of this, add a new migration.
--
-- Where this migration has been applied is recorded in docs/environments.md and
-- evidence/, not here -- a status note kept in this file goes stale without
-- anyone noticing.

-- ---------------------------------------------------------------------------
-- 1. select
-- ---------------------------------------------------------------------------
--
-- DROPPED: "Owners can read their own tasks", which was
--   for select to authenticated using ((select auth.uid()) = owner_id).
--
-- COVERED BY: "Creators and team members can read a task", which is
--   using ((select auth.uid()) = owner_id
--          or (team_id is not null and public.is_team_member(team_id))).
--
-- In plain English: you can read a task if you created it -- which is the whole
-- of the rule being dropped, word for word, as the first branch -- or if it is in
-- a team you belong to. A strict superset: every row the old rule returned, the
-- new one returns, and it returns some more. Nobody loses sight of anything.
drop policy "Owners can read their own tasks" on public.tasks;

-- ---------------------------------------------------------------------------
-- 2. insert
-- ---------------------------------------------------------------------------
--
-- DROPPED: "Owners can add tasks for themselves", which was
--   for insert to authenticated with check ((select auth.uid()) = owner_id).
--
-- COVERED BY: "You can add a task for yourself, or for a team you belong to",
--   which is
--   with check ((select auth.uid()) = owner_id
--               and (team_id is null or public.is_team_member(team_id))).
--
-- In plain English: you can add a task with your own name on it, either personal
-- or into a team you belong to.
--
-- THIS ONE IS NOT A SUPERSET, AND DROPPING IT IS THE POINT. The old rule said
-- nothing about team_id, so while it stood, insert policies being OR-ed meant it
-- allowed Bob to file a task into Alice's team by sending her team's id with his
-- own name on the row. The expand migration said so in as many words and leaned
-- on the trigger to refuse him in the meantime.
--
-- SO WHAT STOPS WORKING: nothing that ever worked. The set of inserts that
-- actually succeeded before this migration is the policies AND the trigger
-- together -- "owner_id is the caller" from the policy, and "a team_id must name
-- a team the row's owner belongs to" from the trigger's insert branch. For any
-- caller going through the API those two are exactly the new rule's two
-- conditions, because the policy pins owner_id to auth.uid(), so "the row's
-- owner" and "the caller" are the same person.
--
-- AND BOB STILL GETS THE SAME ERROR, which is worth stating because it is the
-- opposite of what you would expect from a policy getting stricter. The trigger
-- is BEFORE ROW, so it refuses his insert before the with check is ever
-- evaluated, exactly as it did before this migration: HTTP 403, "A task can only
-- be added to a team its creator belongs to." The policy is now a second lock on
-- the same door rather than an open one. Nothing in
-- scripts/staging/build-it-15-checks.mjs sees any difference -- not the result,
-- not the message.
drop policy "Owners can add tasks for themselves" on public.tasks;

-- ---------------------------------------------------------------------------
-- 3. update
-- ---------------------------------------------------------------------------
--
-- DROPPED: "Owners can change their own tasks", which was
--   for update to authenticated
--   using ((select auth.uid()) = owner_id)
--   with check ((select auth.uid()) = owner_id).
--
-- COVERED BY: "Creators and team members can change a task", which is
--   using ((select auth.uid()) = owner_id
--          or (team_id is not null and public.is_team_member(team_id)))
--   with check ((team_id is null and (select auth.uid()) = owner_id)
--               or (team_id is not null and public.is_team_member(team_id))).
--
-- In plain English: you can change a task if you created it or if it is in a team
-- you belong to, and after the change it must be either a personal task of your
-- own or a task in a team you belong to.
--
-- using is a strict superset: the dropped rule's whole condition is its first
-- branch. Nobody loses the right to touch a row they could touch before.
--
-- with check is where the two differ. The dropped rule's with check was just
-- "the row is yours", which is WIDER in two situations:
--
--   (a) the creator filing their own task into a team they do not belong to.
--       Refused before this migration and refused after it, by the trigger,
--       with the same sentence both times -- "A task can only be moved into a
--       team its creator belongs to." BEFORE ROW again: the wider with check
--       never got a say. Nothing changes.
--
--   (b) THE STRANDED TASK, and this is THE ONE ANSWER THIS MIGRATION CHANGES.
--       A task whose team_id names a team its creator is NOT in. Before this
--       migration its creator could tick and rename it, because the dropped rule
--       only asked whether the row was theirs. After it they cannot: the row is
--       not personal and they are not in its team, so the surviving with check
--       matches neither branch and the update is refused with "new row violates
--       row-level security policy for table tasks".
--
-- WHAT THE CREATOR OF A STRANDED TASK CAN STILL DO, because "cannot tick or
-- rename" sounds worse than it is and the difference matters:
--   * SEE it -- the select rule's first branch is "you created it";
--   * MOVE IT BACK TO PERSONAL -- the trigger allows it (they are the creator)
--     and the with check's first branch then matches (personal, and theirs);
--   * RENAME AND TICK IT once it is personal again, by the same branch;
--   * DELETE it -- the delete rule in section 4 is unchanged.
-- So nothing is locked away and no work is stuck. What they cannot do is keep
-- changing it while it sits in a team they are no longer part of.
--
-- HOW A STRANDED TASK COMES ABOUT, so the size of (b) is not guessed at. Only one
-- path exists in this database: "Team owners can remove a member from their team"
-- (20261002122203_team_rules.sql) lets a team's owner delete a team_members row,
-- and a task that member had filed into that team keeps its team_id. No screen
-- calls it -- checked across web/src on 2026-10-02: the only two mentions of
-- team_members are comments -- so today that happens only by hand, through the
-- API or the SQL editor. Deleting the TEAM strands nothing: team_id is on delete
-- set null, so those tasks come back as personal and the first with check branch
-- covers them.
--
-- WHY THAT IS THE RULE WE WANT, rather than something to patch around.
-- docs/plan.md feature 4 says every member of a team can tick and rename that
-- team's tasks. Someone who has been removed from the team is not a member, so
-- the surviving rule is the plan's rule, and the dropped one was the anomaly --
-- the only rule left in the table that still answered "is it yours?" about a row
-- that had become somebody else's team's business.
drop policy "Owners can change their own tasks" on public.tasks;

-- ---------------------------------------------------------------------------
-- 4. delete -- NOT DROPPED
-- ---------------------------------------------------------------------------
--
-- "Owners can remove their own tasks" from 20260927182443_create_tasks.sql stays,
-- and this comment is the whole reason this section exists: it is the easiest
-- thing in this file to get wrong, because the policy's name matches the other
-- three and its condition is the same owner-only expression.
--
-- It stays because it is THE ONLY DELETE POLICY ON public.tasks. The expand
-- migration deliberately added none -- "Owners can remove their own tasks already
-- says exactly what this feature wants" -- so dropping it would leave the table
-- with no delete rule at all, and row-level security refuses what no policy
-- allows. Nobody could delete any task, their own included, and the only sign of
-- it through the API would be deletes quietly matching zero rows.
--
-- It is also the rule docs/plan.md asks for: "only the person who created a task
-- can delete it, so nobody loses an entry because somebody else tidied up."

-- ---------------------------------------------------------------------------
-- The trigger is untouched, on purpose
-- ---------------------------------------------------------------------------
--
-- tasks_enforce_column_rules stays exactly as part 1 created it. It was never
-- scaffolding for the expand phase, and the expand migration says so: it is the
-- only thing that enforces the column limits -- owner_id, id and created_at never
-- change, and team_id moves only by the creator and only to a team they belong
-- to -- and no policy can express any of that, because a policy sees a finished
-- row and cannot compare it with the old one column by column. Running BEFORE the
-- with check, it is also what keeps every refusal message in this table the same
-- as it was yesterday.
--
-- Its insert branch keeps earning its place for a second reason: it asks about the
-- ROW'S OWNER, not the caller, so it still refuses an incoherent row written by
-- hand in the SQL editor, where auth.uid() is null and the policies do not apply
-- at all.

-- ---------------------------------------------------------------------------
-- What public.tasks allows after this migration
-- ---------------------------------------------------------------------------
--
--   select  "Creators and team members can read a task"
--           the creator, and every member of the task's team.
--   insert  "You can add a task for yourself, or for a team you belong to"
--           yourself only, personal or into a team you belong to.
--   update  "Creators and team members can change a task"
--           the creator and every member of the task's team may change it; the
--           finished row must be your own personal task or in a team you are in.
--   delete  "Owners can remove their own tasks"
--           the creator, and nobody else.
--
-- Four policies, one per command, every one limited to the authenticated role --
-- so a signed-out caller matches none of them and sees nothing. Plus the trigger,
-- for the columns.
