-- A paid Team plan: entitlements, the processed-event log, and the one function
-- that answers "how many people may be in this team". docs/plan.md, "A paid Team
-- plan, and the first team size limit", added 2026-10-14 with the owner's
-- decision already in it: BUILD AND TEST ENTIRELY IN STRIPE'S SANDBOX, and do
-- not create live keys.
--
-- THIS MIGRATION IS THE DATABASE CHANGE ALONE. It adds two tables and two
-- functions. Nothing in it talks to Stripe, nothing in it is reachable by a
-- person, and no existing behaviour changes until the Edge Functions in this
-- same pull request are deployed -- which they are not, by anybody, as part of
-- this change.
--
-- EXPAND ONLY. Two new tables and two new functions; no existing table, column,
-- constraint, index, policy, trigger, function or grant is altered or dropped.
--
-- DO NOT EDIT THIS FILE once it has been applied anywhere. A migration is
-- applied once; editing an applied one leaves the repository and every database
-- that has already run it silently disagreeing, and the edit reaches none of
-- them. To change any of this, add a new migration.
--
-- Where this migration has been applied is recorded in docs/environments.md and
-- evidence/, not here. On the day it was written it had been applied NOWHERE:
-- not local, not staging, not production.
--
-- ---------------------------------------------------------------------------
-- THE ONE SENTENCE THIS WHOLE FILE IS WRITTEN TO MAKE TRUE
-- ---------------------------------------------------------------------------
--
-- NOTHING A PERSON CAN REACH MAY WRITE WHAT THAT PERSON HAS PAID FOR.
--
-- docs/plan.md: "Who can write it: nothing that a person can reach. No user may
-- write any row, ever -- not their own. Only `stripe-webhook` writes."
--
-- That is not a policy choice among several. It is the difference between an
-- app where paid access is decided by Stripe and an app where paid access is
-- decided by whoever can send a PATCH. So `entitlements` has exactly ONE policy,
-- it is a `select` policy, and it is for the row's own owner -- and there is no
-- insert, update or delete policy for anybody at all. A missing policy is a
-- refusal, so the absence IS the rule, and the revokes below mean a caller never
-- reaches row-level security in the first place.

-- ---------------------------------------------------------------------------
-- 1. entitlements -- what one person is entitled to
-- ---------------------------------------------------------------------------
--
-- SIX VALUES AND NOT A SEVENTH. docs/plan.md: "Nothing about a card, no last
-- four digits, no amount, no invoice, no address. A row says what this person is
-- entitled to and when that runs out, and is incapable of saying what they paid
-- or with what."
--
-- That is the same discipline usage_counts was given -- four values, so the row
-- "is incapable of saying more" -- applied to the one table in this app that a
-- payments company writes into. It is easy to let a billing table grow an
-- `amount`, a `currency`, a `last4` and an `invoice_url`, and every one of them
-- would be a fact about somebody's money held in a database that has no need of
-- it. Stripe holds those. We hold what the app has to ASK.
create table public.entitlements (
  -- One row per person, so the primary key is the person. Not a surrogate id:
  -- there is exactly one answer to "what is this person entitled to", and a
  -- table that could hold two would need a rule about which one wins.
  --
  -- ON DELETE CASCADE, so the row goes when the account goes -- which is what
  -- docs/plan.md promises about every row keyed to a person, and what
  -- docs/deletion.md's step list now inherits without a step of its own.
  user_id uuid primary key references auth.users (id) on delete cascade,

  -- WHAT THEY HAVE. A fixed list, for the same reason usage_counts' feature
  -- column has one: a typo at a call site is refused by the database rather
  -- than quietly creating a plan nothing recognises.
  --
  -- 'free' is a real value rather than the absence of a row, because the two
  -- mean different things: no row means nobody has ever started a checkout, and
  -- 'free' means Stripe has told us this person is not currently paying. Both
  -- get the free limit; only one of them has a Stripe customer worth keeping.
  plan text not null default 'free'
    constraint entitlements_plan_allowed check (plan in ('free', 'team')),

  -- STRIPE'S OWN WORD FOR THE SUBSCRIPTION'S STATE, kept as Stripe says it
  -- rather than translated into ours. The list is Stripe's documented set of
  -- subscription statuses; 'none' is ours, for a row that exists because a
  -- checkout was started and has no subscription behind it yet.
  --
  -- WHY NOT A BOOLEAN. "Is this person paid up" is a question with more than
  -- two answers -- past_due and unpaid are people whose card failed and who
  -- have not cancelled -- and collapsing them here would mean this table could
  -- not tell a lapse from a cancellation. What counts as "active enough" is
  -- decided in one place, team_member_limit() below, and not by the shape of
  -- this column.
  status text not null default 'none'
    constraint entitlements_status_allowed check (
      status in (
        'none', 'trialing', 'active', 'past_due', 'canceled',
        'incomplete', 'incomplete_expired', 'unpaid', 'paused'
      )
    ),

  -- When the thing they have paid for runs out. Null when there is no
  -- subscription. Used as a second condition on access below, so that a row
  -- left saying 'active' by a webhook we never received cannot grant a larger
  -- team forever.
  current_period_end timestamptz,

  -- THE TWO STRIPE IDENTIFIERS. Not secrets -- they identify records in
  -- Stripe's system and grant nothing on their own -- but they are the only
  -- link between a person here and a person there, so the customer id is
  -- unique: two of our accounts pointing at one Stripe customer would mean a
  -- webhook could not say whose access to change.
  stripe_customer_id text unique,
  stripe_subscription_id text unique,

  -- When the webhook last changed this row. Not when the person did anything:
  -- a person cannot change this row at all.
  updated_at timestamptz not null default now()
);

comment on table public.entitlements is
  'What one person is entitled to, written ONLY by the stripe-webhook function holding the service-role key. Readable by that person alone; no policy, and no privilege, lets anybody write it. Six values and nothing about a card, an amount or an invoice.';

comment on column public.entitlements.plan is
  'free or team. A fixed list so a typo is refused rather than creating a plan nothing recognises.';

comment on column public.entitlements.status is
  'Stripe''s own subscription status, plus ''none'' for a row with no subscription behind it. Kept untranslated so a lapse can be told from a cancellation; what counts as active is decided in team_member_limit().';

comment on column public.entitlements.current_period_end is
  'When the paid period ends. Checked as well as status, so a row left saying active by a webhook that never arrived cannot grant a larger team forever.';

-- ---------------------------------------------------------------------------
-- 2. stripe_events -- so the same event is never acted on twice
-- ---------------------------------------------------------------------------
--
-- STRIPE RETRIES. That is the whole reason this table exists, and it is not a
-- precaution against something unlikely: a webhook that answers slowly, or
-- answers 500 once, is sent the same event again. Without this, a retry of a
-- subscription event is a second write of the same fact -- harmless here by
-- luck rather than by design, and not harmless in general.
--
-- THE UNIQUE CONSTRAINT IS THE MECHANISM, not a check in the function. An
-- `if not exists` followed by an insert is two statements with a gap in the
-- middle, and two retries arriving at once fit through that gap. One insert
-- that the database refuses is the version with no gap -- the same argument
-- count_daily_use rests on, written down in 20261008115900_usage_counts.sql.
create table public.stripe_events (
  -- Stripe's event id, which is Stripe's and is unique in Stripe's system.
  -- It is the primary key here because it is the identity of the thing: there
  -- is no version of this table where two rows share an event id.
  event_id text primary key,

  -- The event's type, kept for one reason: so somebody reading this table can
  -- tell what has been happening without opening Stripe. It holds no personal
  -- data -- 'customer.subscription.updated' is a shape, not a person.
  event_type text not null,

  processed_at timestamptz not null default now()
);

comment on table public.stripe_events is
  'Every Stripe event id this app has already processed, so a retry is ignored. The primary key IS the idempotency mechanism: one insert the database refuses, rather than a check and an insert with a gap between them. No personal data; unreachable by any app user.';

-- ---------------------------------------------------------------------------
-- 3. The team size limit, which is the only thing the money changes
-- ---------------------------------------------------------------------------
--
-- 10, or 25 for a team whose OWNER holds an active Team plan. docs/plan.md:
-- "A team may have 10 members. A team whose owner holds an active Team plan may
-- have 25. That is the whole of what the money buys in this version."
--
-- THE NUMBERS LIVE HERE AND NOT IN limits.ts, and that is deliberate rather
-- than inconsistent. supabase/functions/_shared/limits.ts holds the two DAILY
-- limits because they are read by Edge Functions and nothing else. This one is
-- a question about rows -- "how many members, and what is this team's owner
-- entitled to" -- and the honest place for it is beside the rows, where it can
-- be answered in one statement without a function first fetching an entitlement
-- and then counting members and then comparing. That is also the shape the
-- upload count took when the same question came up on 2026-10-12: the limit
-- goes where the thing it limits is.
--
-- `security definer` BECAUSE A CALLER MUST NOT BE ABLE TO READ THE ANSWER'S
-- INGREDIENTS. A member of a team may not read its owner's entitlements row,
-- and must not need to: they ask this function for a number and get a number.
create or replace function public.team_member_limit(p_team_id uuid)
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when exists (
      select 1
      from public.teams t
      join public.entitlements e on e.user_id = t.owner_id
      where t.id = p_team_id
        and e.plan = 'team'
        -- ACTIVE ENOUGH, DECIDED IN ONE PLACE. 'trialing' counts because a
        -- trial is a thing Stripe considers in force. past_due and unpaid do
        -- NOT: a card that has failed is not a card that has paid, and the
        -- honest answer is to fall back to the free limit rather than to keep
        -- granting a larger team indefinitely.
        and e.status in ('active', 'trialing')
        -- AND THE CLOCK, as well as the word. A row left saying 'active' by a
        -- webhook that never arrived is exactly the failure this second
        -- condition exists for: access stops when the paid period ends,
        -- whether or not anybody told us.
        and e.current_period_end is not null
        and e.current_period_end > now()
    ) then 25
    else 10
  end;
$$;

comment on function public.team_member_limit(uuid) is
  'How many members this team may have: 25 when its owner holds an active or trialing Team plan whose period has not ended, otherwise 10. security definer because a member must not be able to read their team owner''s entitlements row in order to learn the number.';

-- ---------------------------------------------------------------------------
-- 4. What a person may read about themselves
-- ---------------------------------------------------------------------------
--
-- ONE READ, OF ONE ROW, FOR ITS OWNER. Returned by a function rather than by a
-- table grant, for the same reason my_ai_suggestions() exists: a grant of
-- `select` on the table would also be a grant a future policy could widen by
-- accident, and a function returns exactly the columns the app needs with no
-- route to the others.
--
-- IT RETURNS THE LIMIT TOO, so a screen never computes one. A screen that did
-- its own arithmetic on plan and status would be a second place the rule lives,
-- and the two would drift.
create or replace function public.my_entitlement()
returns table (
  plan text,
  status text,
  current_period_end timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select e.plan, e.status, e.current_period_end
  from public.entitlements e
  where e.user_id = (select auth.uid());
$$;

comment on function public.my_entitlement() is
  'The caller''s own entitlement, and nobody else''s. Returns no row when the caller has never started a checkout, which the app reads as the free plan.';

-- ---------------------------------------------------------------------------
-- 5. Row-level security, and the privileges that matter more
-- ---------------------------------------------------------------------------
--
-- Both tables get RLS enabled. On entitlements that is load-bearing, because
-- there IS one policy. On stripe_events it is the belt to the revokes' braces:
-- there is no policy at all, so RLS alone would refuse everybody.
alter table public.entitlements enable row level security;
alter table public.stripe_events enable row level security;

-- THE ONE POLICY IN THIS MIGRATION. Select, for the row's own owner, and
-- nothing else -- no insert, no update, no delete, for anybody.
--
-- WHAT ITS ABSENCE MEANS, said out loud because an absence is easy to read as
-- an oversight: a table with RLS on and no insert policy refuses every insert,
-- including the caller's own. So "no user may write any row, ever" is enforced
-- by there being nothing here to permit it, and a later migration that added an
-- update policy would be the thing to argue with.
create policy "You can read your own entitlement"
  on public.entitlements
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

-- ---------------------------------------------------------------------------
-- 6. The grants, written out rather than inherited
-- ---------------------------------------------------------------------------
--
-- Supabase has historically granted select/insert/update/delete on new tables
-- in `public` to anon and authenticated, and a change to that default is
-- scheduled. Writing every revoke explicitly means this file reads the same way
-- on a project with either default, and a reader does not have to know which
-- one they are looking at. On a project with the new defaults every revoke is a
-- no-op that succeeds.
revoke all on table public.entitlements from public;
revoke all on table public.entitlements from anon;
revoke all on table public.entitlements from authenticated;
revoke all on table public.entitlements from service_role;

revoke all on table public.stripe_events from public;
revoke all on table public.stripe_events from anon;
revoke all on table public.stripe_events from authenticated;
revoke all on table public.stripe_events from service_role;

-- AND THEN GIVE service_role BACK EXACTLY WHAT THE WEBHOOK NEEDS, which is the
-- one place this file differs from usage_counts -- that table gives service_role
-- nothing at all, because everything it does happens inside a function.
--
-- Here the webhook genuinely writes rows, so it genuinely needs the privilege.
-- What it is NOT given is anything on the other tables it has no business in,
-- and what no OTHER role is given is anything at all.
--
-- `delete` IS GRANTED ON stripe_events AND NOT ON entitlements, and the
-- difference is the point:
--
--   * stripe_events is a log with a window. Nothing in this migration prunes it
--     -- there is no scheduled job in this app and this change does not invent
--     one -- but the webhook is the thing that would, and a table nobody can
--     ever delete from is a table that grows forever.
--   * entitlements is deleted by ONE thing only: the cascade from auth.users
--     when an account goes. A webhook that could delete an entitlement could
--     silently remove somebody's paid access, and there is no Stripe event for
--     which "delete our record" is the right answer -- a cancellation sets the
--     status, it does not forget the customer.
grant select, insert, update on table public.entitlements to service_role;
grant select, insert, delete on table public.stripe_events to service_role;

-- THE TWO FUNCTIONS, AND WHO MAY RUN THEM.
--
-- my_entitlement() is for the signed-in person and is useless to anybody else:
-- it reads auth.uid() and returns that person's row. anon gets nothing, because
-- a signed-out caller has no uid and the function would answer an empty set --
-- which is harmless and is still a call nobody has a reason to make.
revoke all on function public.my_entitlement() from public;
revoke all on function public.my_entitlement() from anon;
grant execute on function public.my_entitlement() to authenticated;

-- team_member_limit() is called by the two Edge Functions, as service_role,
-- immediately before they let somebody into a team.
--
-- IT IS NOT GRANTED TO authenticated, and that is a decision rather than an
-- omission. The number is not a secret -- 10 and 25 are written in
-- docs/plan.md -- but the function takes a TEAM ID, so a signed-in caller who
-- could run it could ask it about any team id they liked and learn whether that
-- team's owner is paying. That is a fact about somebody else's money, leaked one
-- yes-or-no at a time, in exchange for saving a screen one round trip. The
-- screen asks my_entitlement() about ITSELF instead.
revoke all on function public.team_member_limit(uuid) from public;
revoke all on function public.team_member_limit(uuid) from anon;
revoke all on function public.team_member_limit(uuid) from authenticated;
grant execute on function public.team_member_limit(uuid) to service_role;
