-- A daily count of attachment uploads: 30 per person per UTC day, written by a
-- trigger on storage.objects. docs/plan.md, "Files attached to a task" ->
-- "AN UPLOAD IS NOW COUNTED TOO -- 30 A DAY PER PERSON", the owner's decision of
-- 2026-10-11, and the mechanism decided on 2026-10-12.
--
-- Build it 25 part 2b, and the LAST of Build it 25's code. Part 2a
-- (20261012094500) is the 500-task cap and the four input constraints.
--
-- THIS MIGRATION IS THE DATABASE CHANGE ALONE. No screen, no server function and
-- no action is touched. What a person sees when the thirty-first upload is
-- refused is the next pull request's, and section 6 is why that is harder here
-- than it was for the cap.
--
-- DO NOT EDIT THIS FILE once it has been applied anywhere. A migration is
-- applied once; editing an applied one leaves the repository and every database
-- that has already run it silently disagreeing, and the edit reaches none of
-- them. To change any of this, add a new migration.
--
-- Where this migration has been applied is recorded in docs/environments.md and
-- evidence/, not here. On the day it was written it had been applied NOWHERE:
-- not local, not staging, not production.
--
-- ---------------------------------------------------------------------------
-- WHY A TRIGGER AND NOT A COUNT INSIDE THE POLICY
-- ---------------------------------------------------------------------------
--
-- The owner's decision of 2026-10-12, and it reverses what docs/rate-limits.md
-- proposed. The upload path has no Edge Function in it -- the browser uploads
-- straight to Storage as the signed-in person, decided 9 October -- so the count
-- has to be written by something in the database.
--
-- A COUNT INSIDE public.attachments_may_add() WAS THE OBVIOUS PLACE AND IS THE
-- WRONG ONE, for a reason that is not in docs/plan.md and was found while
-- designing this: that function is granted EXECUTE to `authenticated`, because
-- the INSERT policy names it and a policy's expression runs with the caller's
-- privileges. A function in `public` with that grant is published by PostgREST as
-- an RPC -- so a signed-in person could call it thirty times and spend their own
-- day without uploading anything, and every direct call would COMMIT, because
-- there is no outer INSERT to roll it back.
--
-- The realistic harm is not somebody attacking themselves. It is a future screen:
-- anything that greyed out the upload box by asking "can I add a file?" would
-- spend a slot on every page load and quietly halve everybody's allowance.
--
-- A TRIGGER HAS NEITHER PROBLEM. It fires only on a real INSERT, it cannot be
-- called directly -- PostgreSQL answers "trigger functions can only be called as
-- triggers" -- and it can raise a message rather than only answering false.
--
-- AND IT IS THE SHAPE 20261008191804_attachments_bucket.sql ALREADY ARGUES FOR,
-- in its own words about the task-deletion refusal: "It is a trigger rather than
-- a policy because a policy is not evaluated for service_role, for the table's
-- owner, or for a cascade." The same sentence is the reason this one needs
-- section 3's early return -- a trigger fires for service_role too, and here
-- that must NOT count.
--
-- ---------------------------------------------------------------------------
-- WHAT A REFUSED OR FAILED UPLOAD COSTS: NOTHING. The count is written in the
-- SAME TRANSACTION as the row.
-- ---------------------------------------------------------------------------
--
-- A BEFORE INSERT trigger runs inside the statement it is checking, so the count
-- it writes is rolled back with everything else if the row does not land -- the
-- INSERT policy refusing it, a unique violation, a failure later in the same
-- transaction. docs/plan.md's own test of this: "A count kept on a refused upload
-- is the wrong way round; a count lost on a successful one is worse."
--
-- MEASURED, NOT ARGUED. evidence/build-it-25-upload-count.md races this exact
-- trigger on a throwaway PostgreSQL 17.10 database:
--
--   30 uploads by a signed-in person        all 30 allowed, usage_counts = 30
--   the 31st                                 refused, 54000, nothing written
--   a duplicate path (unique violation
--     AFTER the trigger has counted)         rolled back, the count unchanged
--   a failure later in the same transaction  rolled back, the count unchanged
--   40 files in ONE service-role statement   all 40 land, NOTHING counted
--
-- THIS IS A DEPARTURE FROM THE RULE THE OTHER TWO COUNTED FEATURES FOLLOW, and
-- it is deliberate. docs/plan.md's rule for those is "the count is written
-- immediately before the paid call and is never given back", because an Edge
-- Function cannot un-send an email or un-spend a token. An upload spends nothing
-- at a vendor -- it spends this project's own traffic -- and a refused INSERT
-- never reached the bucket, so there is nothing to have spent. The two features
-- that cost money keep their rule; this one cannot have it and does not need it.

-- ---------------------------------------------------------------------------
-- 0. THE PRE-CHECK: nothing below runs if this role may not create the trigger
-- ---------------------------------------------------------------------------
--
-- THE ONE THING NOBODY KNEW WHEN THIS WAS WRITTEN: whether the role that applies
-- migrations may create a trigger on storage.objects, which is a Supabase-managed
-- table this project does not own. 20261008191804_attachments_bucket.sql carries
-- the weaker version of the same question about SELECT, and a local sandbox
-- cannot settle either -- a local `postgres` is a superuser and owns everything.
--
-- SO THIS MIGRATION ASKS BEFORE IT CREATES ANYTHING, and the reason it can is a
-- fact that was measured rather than remembered: CREATE TRIGGER needs the
-- **TRIGGER privilege on the table, NOT ownership of it.**
-- evidence/build-it-25-upload-count.md section 2 is the run -- a non-owner role
-- with `grant trigger` created one on a table still owned by postgres, and
-- `has_table_privilege(role, table, 'TRIGGER')` answered false before the grant
-- and true after.
--
-- WHAT THAT BUYS, which is what the owner asked for: a push that is going to be
-- refused is refused HERE, at the first statement, with a message that says what
-- is missing -- and NOTHING in this migration has been applied. Not a constraint,
-- not a function, not a trigger. The alternative is finding out at the last
-- statement with two objects already created.
--
-- AND IF IT FAILS LATER ANYWAY, which this cannot rule out, the order below is
-- chosen so that what is left behind is INERT:
--
--   the widened constraint   accepts a word nothing writes
--   the trigger function     is called by nothing
--
-- Neither changes what any upload does. The one ordering that would have been
-- dangerous is the opposite one -- the trigger live before the constraint allows
-- 'uploads' -- which would refuse every upload with a check violation. That is
-- why the constraint goes first even though it reads like the smaller change.
do $$
begin
  -- The table itself, before the privilege: to_regclass answers null rather than
  -- raising, so a missing table gets this sentence instead of a bare "relation
  -- does not exist" from inside has_table_privilege.
  if to_regclass('storage.objects') is null then
    raise exception
      'Build it 25 part 2b needs the table storage.objects and it is not there. Nothing in this migration has been applied.'
      using errcode = '42P01',
            hint = 'This migration belongs on a Supabase project, where Storage creates that table. On a bare PostgreSQL database there is nothing for it to attach to.';
  end if;

  if not has_table_privilege(current_user, 'storage.objects', 'TRIGGER') then
    raise exception
      'Build it 25 part 2b needs the TRIGGER privilege on storage.objects, and the role applying it (%) does not hold it. NOTHING IN THIS MIGRATION HAS BEEN APPLIED.',
      current_user
      using errcode = '42501',
            hint = 'CREATE TRIGGER needs the TRIGGER privilege on the table and not ownership of it, so this is a grant rather than a change of owner. If it cannot be granted, the fallback is docs/plan.md''s other option: count inside public.attachments_may_add() and accept that a signed-in caller can spend their own allowance by calling it directly. That is a different migration, not a change to this one.';
  end if;

  raise notice
    'TRIGGER privilege on storage.objects: held by %. Proceeding.', current_user;
end;
$$;

-- ---------------------------------------------------------------------------
-- 1. A third feature word
-- ---------------------------------------------------------------------------
--
-- usage_counts_feature_allowed is a check constraint naming a FIXED LIST, and
-- 20261008115900_usage_counts.sql says why: "ADDING A FEATURE NEEDS A NEW
-- MIGRATION, which is the point of a fixed list. A feature word is also the key
-- the counting function is called with, so a typo at a call site --
-- 'ai_suggestion', 'invite' -- is refused by the database rather than quietly
-- counted in a fourth bucket that no limit watches."
--
-- docs/plan.md asked for exactly this, in advance: "It needs a new migration,
-- because `usage_counts_feature_allowed` is a check constraint naming two words
-- and the point of a fixed list is that adding to it is deliberate and visible."
--
-- 'uploads', chosen by the owner on 2026-10-12. The two words beside it name the
-- thing being counted -- `ai_suggestions`, `invitations` -- and 'attachments'
-- would have named the bucket rather than the use.
--
-- A DROP AND A RE-ADD, because a check constraint cannot be widened in place.
-- This is the one statement in Build it 25 that drops something, and it is a
-- constraint this project created, on a table only this project writes. The
-- re-add validates every existing row against the wider list, which cannot fail:
-- a wider list accepts everything the narrower one did.
--
-- AND THE FIRST COUNT HERE THAT IS NOT ABOUT MONEY. docs/plan.md: "The two above
-- bound money per press; an upload spends traffic. So this section's own title
-- stops being the whole of what it covers." Nothing about usage_counts' shape
-- changes: four columns, and the row still cannot say which file, which task or
-- what time of day.
alter table public.usage_counts
  drop constraint usage_counts_feature_allowed;

alter table public.usage_counts
  add constraint usage_counts_feature_allowed
  check (feature in ('ai_suggestions', 'invitations', 'uploads'));

comment on column public.usage_counts.feature is
  'Which limited feature: ai_suggestions, invitations or uploads, and nothing else -- usage_counts_feature_allowed is the fixed list. Adding a feature needs a new migration, on purpose. uploads was added 2026-10-12 and is the first of the three that is not about money: it bounds traffic rather than a bill.';

-- ---------------------------------------------------------------------------
-- 2. The trigger function
-- ---------------------------------------------------------------------------
--
-- THE NUMBER LIVES HERE, AND THAT DEPARTS FROM docs/plan.md -- the owner's
-- decision of 2026-10-12, taken with the reason in front of them. That section
-- says of this third number: "It goes in the same config file, so the rule above
-- holds: three numbers, one place." It cannot.
-- supabase/functions/_shared/limits.ts is TypeScript read by two Edge Functions;
-- a trigger inside PostgreSQL cannot read it, and putting 30 there as well would
-- be a second copy that nothing reads -- which is worse than one copy in an
-- unexpected place. limits.ts carries a comment pointing here, and
-- scripts/screen-state-check.mjs asserts that `uploads` is NOT one of its keys,
-- so the departure is checked rather than remembered.
--
-- 30, from docs/plan.md: "Three files per task at ten tasks in a day is a
-- volunteer having an unusually busy morning; thirty-one is something nobody
-- designed for." It sits beside the two 20s rather than matching them because it
-- bounds a different thing -- not money per press, but traffic.
--
-- security definer, and here that is doing TWO jobs rather than one:
--
--   * public.count_daily_use() has EXECUTE granted to service_role and revoked
--     from anon, authenticated and PUBLIC. Running as this function's owner --
--     postgres, which owns that function -- is what lets the count happen at all
--     for a caller who holds no privilege on it. SO NO NEW GRANT IS NEEDED, and
--     `authenticated` still cannot count anything itself. Measured: section 6 of
--     the evidence file shows all thirty uploads counting while
--     has_function_privilege('authenticated', ...) is false.
--   * it reads nothing the caller may not read, so unlike attachments_may_add()
--     that is not the reason. It is the privilege, and nothing else.
--
-- The house guards that come with it, and the reasoning is
-- 20261002122203_team_rules.sql's, unchanged:
--
--   set search_path = ''  so no schema is searched implicitly. A function running
--                         with more rights than its caller must not resolve a
--                         name through a path somebody else can change.
--   schema-qualified      the consequence: public.count_daily_use and auth.uid()
--                         are each written in full.
create function public.attachments_count_upload()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  -- The day's limit. See the note above about why it is here and not in
  -- supabase/functions/_shared/limits.ts.
  c_uploads_per_day constant integer := 30;

  l_uploader uuid := auth.uid();
begin
  -- -----------------------------------------------------------------
  -- NOT OUR BUCKET: nothing to count, and nothing to refuse.
  -- -----------------------------------------------------------------
  --
  -- `is distinct from` rather than `<>`, so a null bucket_id takes this branch
  -- instead of making the comparison unknown and falling through to a count
  -- against a row that is not an attachment. The column is NOT NULL on Supabase,
  -- which makes this belt-and-braces rather than a fix -- and a trigger that fired
  -- on every object in every bucket a later feature adds is exactly the kind of
  -- thing that should fail towards doing nothing.
  if new.bucket_id is distinct from 'attachments' then
    return new;
  end if;

  -- -----------------------------------------------------------------
  -- NOBODY SIGNED IN: NOT COUNTED, AND NOT REFUSED.
  -- -----------------------------------------------------------------
  --
  -- THIS IS THE BRANCH THE RESTORE DEPENDS ON, and it is the opposite of the
  -- fail-closed direction every other function in this schema takes -- so it is
  -- argued rather than asserted.
  --
  -- auth.uid() is null for a caller using the service-role key and for an admin
  -- connection. scripts/backup/restore-backup.mjs puts a person's files back with
  -- that key, and docs/restore-runbook.md is the procedure. A RESTORE OF MORE THAN
  -- THIRTY FILES MUST WORK -- and it must not matter whose files they are, or what
  -- day it is, or what any of those people's counts happen to say. A fail-closed
  -- branch here would make the thirty-first file of a recovery refuse itself, on
  -- the worst day this project will ever have.
  --
  -- WHY THAT IS SAFE RATHER THAN A HOLE: this is a trigger, so it fires for
  -- service_role -- there is no row-level security to bypass. What reaches here
  -- with no uploader is something already holding the service-role key, and
  -- 20261008191804_attachments_bucket.sql's section 5 already records what such a
  -- caller can do: it bypasses every policy on storage.objects, and an object it
  -- writes "has no owner_id at all, so it belongs to nobody's 100 MB". A daily
  -- count is not what stands between that key and this bucket, and pretending it
  -- is would cost a restore and buy nothing.
  --
  -- Measured: 40 files in one committed service-role statement, nothing counted.
  if l_uploader is null then
    return new;
  end if;

  -- -----------------------------------------------------------------
  -- AND OTHERWISE, ONE USE.
  -- -----------------------------------------------------------------
  --
  -- count_daily_use does the comparison and the increment in ONE statement, which
  -- is the whole reason it exists: 20261008115900_usage_counts.sql's "Two calls at
  -- the same moment must not both pass a limit with room for one." So two uploads
  -- landing together cannot both be the thirtieth.
  --
  -- AN ERROR FROM IT IS A REFUSAL AND NOT A PASS, and here that is free rather
  -- than something to remember: this is plpgsql with no exception handler, so a
  -- raise from inside count_daily_use -- an unknown feature word, a user id with
  -- no account -- leaves this function, aborts the INSERT, and the upload does not
  -- happen. The same fail-closed direction the two Edge Functions have to write
  -- out by hand.
  if not public.count_daily_use(l_uploader, 'uploads', c_uploads_per_day) then
    -- THE SENTENCE IS docs/plan.md's, character for character, and it is the SAME
    -- one supabase/functions/_shared/limits.ts sends for the other two features.
    -- One sentence for the daily limit, wherever it comes from.
    -- scripts/screen-state-check.mjs compares this copy with that one.
    --
    -- IT NAMES NOTHING ELSE, which matters more here than in a TypeScript file:
    -- docs/plan.md forbids a file name in an error -- "a storage error is reported
    -- with its code and the operation, never with the path or the name" -- and this
    -- message has no path, no file name, no count and no limit in it. There is
    -- nothing in it for a name to travel in.
    --
    -- 54000 is `program_limit_exceeded`, chosen because it is distinguishable from
    -- the two codes this bucket's own rules already produce: 42501 for a policy
    -- refusal and 23514 for a check constraint. It is a PROPOSAL rather than a
    -- house convention -- the only other raising trigger in this project reuses
    -- 23503 -- and WHETHER IT SURVIVES THE STORAGE API AT ALL IS UNKNOWN. The
    -- browser does not talk to PostgreSQL here; it talks to Storage, which decides
    -- what to make of this. scripts/staging/build-it-25-upload-count-checks.mjs
    -- records the exact status and body, and section 6 says what happens if
    -- neither the code nor the sentence comes through.
    raise exception 'You''ve reached today''s limit. It resets tomorrow.'
      using errcode = '54000';
  end if;

  return new;
end;
$$;

comment on function public.attachments_count_upload() is
  'Trigger on storage.objects. Counts one upload per person per UTC day against a limit of 30, through public.count_daily_use(), and refuses the thirty-first with SQLSTATE 54000. Counts nothing for a bucket other than attachments, and nothing at all when auth.uid() is null -- which is the service-role path, so a restore of more than thirty files still works. The count is written in the same transaction as the row, so a refused or failed upload spends no slot. security definer, because EXECUTE on count_daily_use is granted only to service_role and this runs as its owner instead. The message carries no path, no file name and no number. See docs/plan.md, "Files attached to a task".';

-- EXECUTE on a trigger function is not checked when the trigger fires, and a
-- trigger function cannot be called directly -- PostgreSQL answers "trigger
-- functions can only be called as triggers" -- so none of these grants serves
-- anything and taking them away costs nothing.
--
-- All four are written for the reason 20261008191804_attachments_bucket.sql gives
-- about its own twin: a revoke from PUBLIC does not remove a grant Supabase made
-- to anon and authenticated BY NAME, so revoking from PUBLIC alone leaves two
-- grants behind. They are harmless, and a grant nobody can use is still a grant
-- somebody has to work out is harmless.
revoke execute on function public.attachments_count_upload() from public;
revoke execute on function public.attachments_count_upload() from anon;
revoke execute on function public.attachments_count_upload() from authenticated;
revoke execute on function public.attachments_count_upload() from service_role;

-- ---------------------------------------------------------------------------
-- 3. The trigger
-- ---------------------------------------------------------------------------
--
-- BEFORE INSERT, FOR EACH ROW, and every word of that is load-bearing:
--
--   BEFORE      so the count is written before the row is, and the refusal stops
--               the row rather than undoing it. An AFTER trigger would count a
--               row that a later check might still refuse -- which is the same
--               thing in one transaction, and reads as though it is not.
--   INSERT      and nothing else. An upload is an insert; this bucket's rules
--               permit no UPDATE at all (there is no update policy on it), and a
--               DELETE must never cost anybody a slot -- otherwise deleting a file
--               to make room would spend the room.
--   FOR EACH ROW  so a multi-row insert is counted per row rather than once.
--               Measured: a signed-in multi-row insert of 40 from 0 is refused
--               after the thirtieth, and the whole statement fails -- the same
--               shape part 2a's cap has. Not reachable through the Storage API,
--               which uploads one object per request, and checked because
--               "not reachable today" is not a property of the database.
--
-- NO `when` CLAUSE, deliberately, even though `when (new.bucket_id =
-- 'attachments')` would read well. A `when` clause is evaluated by PostgreSQL
-- before the function is called, which is marginally cheaper -- and it would put
-- HALF of the "which uploads count" rule outside the function, where the comment
-- explaining it cannot live beside it. One place decides, and it is the function.
create trigger attachments_count_upload
  before insert on storage.objects
  for each row
  execute function public.attachments_count_upload();

-- ---------------------------------------------------------------------------
-- 4. What this migration does NOT do
-- ---------------------------------------------------------------------------
--
--   * IT DOES NOT BOUND STORAGE. 100 MB per person and 3 files per task are
--     public.attachments_may_add()'s, called from the INSERT policy, and they are
--     untouched. docs/plan.md: a stock is bounded by a total, a flow by a rate,
--     and this is the rate.
--   * IT DOES NOT BOUND DOWNLOADS. A signed link is made by a server action and
--     nothing counts how many somebody asks for -- docs/rate-limits.md's row 9
--     says so and this does not change it. Egress is spent by reading a file as
--     well as by writing one.
--   * IT COUNTS NOTHING FOR THE SERVICE-ROLE KEY, which is section 2's branch and
--     is the restore's requirement rather than an oversight.
--   * AND IT CHANGES NO SCREEN. The thirty-first upload is refused by the
--     database today and whatever the app says about it is the next pull
--     request's, which section 6 is written for.
--
-- ---------------------------------------------------------------------------
-- 5. The read-backs, for after it is applied
-- ---------------------------------------------------------------------------
--
