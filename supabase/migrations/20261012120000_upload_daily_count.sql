-- None of them reads a row of anybody's data.
--
-- ---------------------------------------------------------------------------
-- 6. WHAT THE SCREEN CANNOT YET RELY ON, which is this file's one open question
-- ---------------------------------------------------------------------------
--
-- THE BROWSER NEVER SEES THIS EXCEPTION. It talks to the Storage API, which talks
-- to PostgreSQL, and what Storage makes of a trigger's exception -- the status,
-- whether the message comes through, whether 54000 appears anywhere -- IS NOT
-- KNOWN. No page read says, and a local database cannot answer it: it is a
-- property of a service.
--
-- So nothing in the next pull request may be written against either the sentence
-- or the code until somebody has looked.
-- scripts/staging/build-it-25-upload-count-checks.mjs section 4 exists to record
-- exactly that: the HTTP status and the body, printed, for the thirty-first
-- upload.
--
-- AND IF NEITHER SURVIVES, the screen still has to tell this refusal from the
-- 3-files-per-task one, which is a different sentence. Two ways that do not
-- depend on Storage passing anything through, in the order they should be tried:
--
--   1. ASK, the way part 2a's cap does. A refused upload is followed by one call
--      to public.attachments_may_add(), which answers whether the TASK and the
--      100 MB still have room. If it says yes, the refusal was not about those --
--      so it was the daily limit. That needs no new function and no new grant,
--      and it is the same "ask rather than infer" shape the owner chose for the
--      cap on 2026-10-12.
--   2. A function the person may ask about their own day, if 1 turns out not to
--      separate the cases cleanly. It would be a new `security definer` reader
--      over usage_counts granted to `authenticated` -- and it needs
--      docs/plan.md changed first, because that plan says in as many words that
--      nobody can see this count through the app, "not even the person whose
--      count it is". That is the owner's call and not a thing to slip in.
--
-- Option 1 is proposed. Neither is built here.
