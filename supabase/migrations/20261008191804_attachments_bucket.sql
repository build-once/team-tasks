-- `contentType` option"
-- (https://supabase.com/docs/guides/storage/uploads/standard-uploads, read
-- 2026-10-08). Both halves of that are chosen by whoever is uploading, so A
-- RENAMED FILE GETS THROUGH. The bucket enforces the refusal, never the
