-- ---------------------------------------------------------------------------
-- 1. The bucket
-- ---------------------------------------------------------------------------
--
-- PRIVATE, which is the first line of the design rather than a setting.
-- `public => false` means there is no address that works: nothing in this
-- bucket can be fetched by URL, and the only route to a file's bytes is a
-- signed link the app asks for on behalf of somebody the SELECT policy below
-- has already admitted. A public bucket would make every rule in this file
-- decoration.
--
-- TWO RESTRICTIONS LIVE ON THE BUCKET ITSELF, so they hold whoever is uploading
-- and whatever screen they came from. Supabase: "If an upload request doesn't
-- meet the above restrictions it will be rejected"
-- (https://supabase.com/docs/guides/storage/buckets/creating-buckets, read
-- 2026-10-08), and the refusal is `InvalidMimeType`, "The specified MIME type is
-- not valid.", 400
-- (https://supabase.com/docs/guides/storage/debugging/error-codes, read
-- 2026-10-08).
--
-- 5 MB IS 5 * 1024 * 1024 = 5242880 BYTES, and the unit is a decision rather
-- than an obvious reading. docs/plan.md's own arithmetic forces it: it says
-- 100 MB is "20 single 5 MB files", which is only true if both numbers use the
-- same unit, and section 5 below uses 100 * 1024 * 1024 for the same reason.
-- 5 MB also sits well under what Supabase would allow -- "For Free projects,
-- the limit can't exceed 50 MB", and a bucket's own limit "can't be higher than
-- this global limit"
-- (https://supabase.com/docs/guides/storage/uploads/file-limits, read
-- 2026-10-08).
--
-- 'image/*' IS A WILDCARD, AND THAT IT WORKS IN THIS COLUMN IS AN INFERENCE
-- rather than a citation. Supabase's documented JavaScript form is
-- `allowedMimeTypes: ['image/*']` (the creating-buckets page above), and the
-- schema page lists `allowed_mime_types` as a column of storage.buckets
-- (https://supabase.com/docs/guides/storage/schema/design, read 2026-10-08).
-- That the column takes the same wildcard spelling as the option is read off the
-- two pages together, and no page read says it. If it turns out not to, every
-- image upload is refused -- a loud, visible failure, not a quiet hole -- and
-- the fix is one migration listing the types in full. Settling it needs one
-- upload of each kind to staging.
--
-- AND WHAT THE TYPE LIMIT DOES NOT PROMISE, which docs/plan.md puts in the plan
