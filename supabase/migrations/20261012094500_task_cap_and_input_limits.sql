-- docs/claims.md and the read-back queries refer to.
--
-- ---------------------------------------------------------------------------
-- THE GUARDS BEFORE EACH CONSTRAINT, AND WHY THEY PRINT ONLY A NUMBER
-- ---------------------------------------------------------------------------
--
-- A check constraint added to a populated table is validated against every
-- existing row, so `alter table` fails with 23514 if any row violates it. That
-- failure names the CONSTRAINT and not how many rows, which is not enough to act
-- on -- and the obvious way to find out more would print a value.
--
-- These columns hold an email address, free text about a person, and task text.
-- All three are on docs/plan.md's sensitive list, and THIS REPOSITORY IS PUBLIC,
-- so a migration's output is public. So each constraint below is preceded by a
-- guard that counts the offending rows and raises with the NUMBER, naming no row
-- and selecting no column's value. There is nothing in the message for a value
-- to travel in.
--
-- The owner also ran the same counts by hand before this was applied -- the four
-- queries are in docs/rate-limits.md section 2 -- and the answers were four
-- zeros on staging and four zeros on production, 12 October 2026. The guards are
-- kept anyway, at the owner's instruction: a count read once is a fact about that
-- moment, and this file runs later and on more than one database.

-- ---------------------------------------------------------------------------
-- 1. At most 500 live tasks per person
-- ---------------------------------------------------------------------------
--
-- docs/plan.md, decided by the owner on 2026-10-11: "at most 500 live tasks per
-- person". And the reason it exists at all, from the same section: adding a task
-- is an INSERT over the Data API with the person's own session, where "Row-level
-- security decides whose rows; two check constraints decide the title; a trigger
-- decides which columns may change. Nothing decides how many, and nothing decides
-- how often."
--
-- LIVE TASKS IS EVERY ROW WITH THAT owner_id, AND THAT IS THE PLAN'S OWN
-- READING, not a simplification of it: "There is no archive in this app and no
-- soft delete, so 'live' and 'in the table' are the same thing -- said anyway,
-- because the first thing somebody would ask is whether ticking a task off makes
-- room. IT DOES NOT: a done task is still on the list, which is the whole point
-- of the list." So `done` is deliberately NOT excluded from the count, and
-- excluding it would be the one reading that paragraph rejects. Checked against
-- the schema as well as the plan: the only state column on public.tasks is
-- `done boolean not null default false` (20260927182443_create_tasks.sql:28),
-- and no migration in this repository contains the word archive, soft delete or
-- deleted_at.
--
-- WHY 500 AND NOT 20: the two daily limits are 20 because they bound money per
-- press. This bounds a LIST, and a list is a thing a person uses. docs/plan.md:
-- "500 is far past any volunteer's morning and far short of a problem for the
-- database ... The number is chosen to be one nobody meets by accident, because
-- a cap a real person hits is a cap that teaches them the app is broken."
--
-- security definer, and NOT because the caller cannot see the rows -- they can:
-- "Creators and team members can read a task" lets the creator read every task
-- they own, whatever team it is in. Two other reasons:
--
--   * it keeps the count out of the SELECT policy's way. A count of public.tasks
--     evaluated as the caller, from inside an INSERT policy on public.tasks,
--     would be a policy on a table reading the same table through another policy
--     on it. Running as the owner -- who bypasses row-level security -- means
--     that question is never asked.
--   * the count must not change meaning if the SELECT policy is ever narrowed.
--     A cap that quietly stopped counting some of a person's own rows would
--     silently become a larger cap.
--
-- The house guards that come with `security definer`, and the reasoning is
-- 20261002122203_team_rules.sql's, unchanged:
--
--   set search_path = ''  so no schema is searched implicitly. A function running
--                         with more rights than its caller must not resolve a name
--                         through a path somebody else can change.
--   schema-qualified      the consequence: public.tasks and auth.uid() are each
--                         written in full.
--
-- IT IS VOLATILE, WHICH IS THE DEFAULT AND IS LOAD-BEARING. Left unwritten the
-- way plpgsql functions in this schema leave it, and said here because marking it
-- `stable` would make the cap DECORATIVE against a single multi-row INSERT -- a
-- stable function is not re-evaluated per row against the rows the statement has
-- already written, so every row would see the count the statement started with.
--
-- MEASURED, NOT ARGUED. evidence/build-it-25-task-cap.md builds this function
-- both ways on a throwaway PostgreSQL 17.10 database and races the same
-- statement at each:
--
--   volatile, 600 rows in one INSERT from 0    REFUSED, 42501, nothing written
--   volatile, 5 rows in one INSERT from 499    REFUSED, and 499 left behind
--   stable,   5 rows in one INSERT from 499    ALL FIVE LAND -- 504
--   stable,   600 rows in one INSERT from 499  ALL 600 LAND -- 1099
--
-- So the `with check` is evaluated per row, and a VOLATILE function in it does
-- see rows inserted earlier in the same statement. A multi-row INSERT over the
-- cap is REFUSED ENTIRELY rather than stopping at 500: the statement fails and
-- nothing partial is written, which is the better of the two outcomes and is why
-- the number in this file needs no second defence against batching.
--
-- NO ADVISORY LOCK, AND 501 IS THEREFORE POSSIBLE. public.attachments_may_add()
-- takes two locks so that two simultaneous uploads take turns, because its limit
-- is 3 and one extra file is a quarter again. Here the equivalent would serialise
-- every task insert a person makes, on the most-used write path in the app, to
-- defend a number chosen so that nobody reaches it. So two requests that arrive
-- at 499 together can both pass and leave 501, and MORE SIMULTANEOUS REQUESTS CAN
-- OVERSHOOT BY MORE -- the overshoot is bounded by how many land at once, not by
-- one. That is accepted: the owner's decision of 2026-10-12, for this reason.
-- Nothing in the app breaks at 501, the next insert is refused, and the person
-- can delete a task.
create function public.tasks_may_add()
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  -- The number, in one place. docs/plan.md's figure, and the only place in the
  -- database it is written.
  c_tasks_per_person constant integer := 500;

  -- WHO IS ASKING IS READ HERE AND IS NEVER AN ARGUMENT, which is the shape
  -- is_active(), my_ai_suggestions() and attachments_may_add() all have: a
  -- function that took a user id could be asked about somebody else.
  l_owner uuid := auth.uid();

  l_tasks integer;
begin
  -- NOBODY SIGNED IN: NO. An admin connection has no auth.uid(), and so does a
  -- caller using the service-role key -- for whom this is not evaluated at all,
  -- because row-level security is not applied to them. Answering no rather than
  -- yes is the fail-closed direction that 20261004114313_suspend_accounts.sql
  -- spells out at length.
  if l_owner is null then
    return false;
  end if;

  select count(*)
    into l_tasks
  from public.tasks t
  where t.owner_id = l_owner;

  -- `<` and not `<=`: the question is whether there is room for ONE MORE, so a
  -- person holding exactly 500 is refused and a person holding 499 is allowed.
  -- With `<=` the cap would be 501.
  return l_tasks < c_tasks_per_person;
end;
$$;

comment on function public.tasks_may_add() is
  'Whether the signed-in person may hold one more task: true when they own fewer than 500 rows in public.tasks. Who is asking is read from auth.uid() inside the body and is never an argument, so it cannot be asked about anybody else. Counts every row they own, done ones included, because docs/plan.md says a done task is still on the list. VOLATILE on purpose: marked stable, the cap would not stop a single multi-row INSERT. It takes no lock, so simultaneous inserts at 499 can leave 501 -- accepted, because the number is chosen so nobody reaches it and a lock would serialise the app''s busiest write path. Not evaluated at all for a caller using the service-role key, which bypasses row-level security. See docs/plan.md, "A ceiling on how many tasks one person can hold".';

-- `authenticated` needs EXECUTE, because the policy below names it and a policy's
-- expression is evaluated with the privileges of the role making the request.
--
-- WHAT A SIGNED-IN CALLER LEARNS BY CALLING IT DIRECTLY, stated because the grant
-- makes it reachable as a PostgREST RPC: one bit about THEMSELVES -- whether they
-- have room for another task. It cannot be asked about anybody else, and IT
-- WRITES NOTHING, so calling it in a loop costs a count and changes no state.
-- That last clause is the difference between this function and the upload counter
-- of part 2b, and it is why this one is safe to expose and that one needed a
-- different mechanism.
--
-- AND THE NEXT PULL REQUEST IS MEANT TO CALL IT. See section 4.
revoke execute on function public.tasks_may_add() from public;
revoke execute on function public.tasks_may_add() from anon;
grant execute on function public.tasks_may_add() to authenticated;

-- ---------------------------------------------------------------------------
-- 2. The INSERT policy on public.tasks gains one condition
-- ---------------------------------------------------------------------------
--
-- The policy is 20261002133637_tasks_join_teams.sql's, and the first two
-- conditions are its own, unchanged and re-stated here because `alter policy`
-- replaces the whole expression and a reader needs to see what was kept:
--
--   (select auth.uid()) = owner_id                     a request cannot create a
--                                                      task for somebody else
--   team_id is null or public.is_team_member(team_id)   and cannot file one into a
--                                                      team it does not belong to
--
-- THE CAP IS LAST, after the two free checks, for the reason
-- 20261008191804_attachments_bucket.sql gives about its own ordering: the limit
-- does a count, and there is no reason to count for a path that was never going
-- to be allowed.
--
-- THE POLICY'S NAME IS 60 BYTES, counted. A policy name is a PostgreSQL
-- identifier and is cut at 63 with only a NOTICE, which a migration run with -q
-- does not show -- the attachments migration records a policy name being
-- truncated exactly that way. This one is under the limit and is unchanged by
-- this file, which is the point of using `alter` rather than a new name.
--
-- WHY A POLICY AND NOT A TRIGGER. docs/plan.md names the policy: "by a
-- `security definer` function called from the INSERT policy -- exactly the shape
-- attachments_may_add() already has ... NOT in a screen, because a screen can be
-- bypassed, and not in an Edge Function, because there is no function in this
-- path". A trigger would also work and would be able to raise its own message;
-- the owner chose the policy on 2026-10-12, and section 4 is how the message is
-- produced without one.
alter policy "You can add a task for yourself, or for a team you belong to"
  on public.tasks
  with check (
    (select auth.uid()) = owner_id
    and (team_id is null or public.is_team_member(team_id))
    and public.tasks_may_add()
  );

-- ---------------------------------------------------------------------------
-- 3. Four bounds on what the server accepts
-- ---------------------------------------------------------------------------
--
-- docs/rate-limits.md section 2 asked the question "what is NOT checked by the
-- database or by a server function" of every field the app writes, and these four
-- are what came back. Each is preceded by its guard, for the reason at the top of
-- this file.

-- 3.1 An invited address has a length bound in the database, not only in code.
--
-- supabase/functions/invite-member/index.ts has refused over 320 characters since
-- it was written, and the column is plain `text` with no bound -- so the rule
-- lives in one place and that place is not the database. `service_role` and the
-- dashboard can both write a longer one.
--
-- 320 is the figure already in the function and in web/src/lib/teams.ts's
-- EMAIL_MAX, so this adds no new number to the project.
--
-- It joins invitations_email_lowercase, invitations_email_not_blank and
-- invitations_email_shape, which are on the column already
-- (20260930193813_create_invitations.sql:72-74).
do $$
declare
  l_bad integer;
begin
  select count(*) into l_bad
  from public.invitations
  where char_length(email) > 320;

  if l_bad > 0 then
    raise exception
      'Cannot add invitations_email_length: % row(s) already hold a longer address. Look at them in the dashboard, by hand -- this message names no row on purpose.',
      l_bad;
  end if;
end;
$$;

alter table public.invitations
  add constraint invitations_email_length
  check (char_length(email) <= 320);

comment on constraint invitations_email_length on public.invitations is
  'At most 320 characters. The same figure invite-member and web/src/lib/teams.ts already use; this is the copy the database keeps, so a write that does not go through the function is bounded too.';

-- 3.2 The owner's reason for a suspension has a length bound.
--
-- THE LIKELIEST OF THE FOUR TO HAVE HAD A VIOLATING ROW, which is why the guard
-- is not a formality: `reason` is unbounded free text TYPED BY THE OWNER IN THE
-- DASHBOARD, and that is the one write path in this app no code checks.
--
-- `reason is null or ...` IS NOT DECORATION. The column is nullable
-- (20261004114313_suspend_accounts.sql:84), and a check that evaluates to
-- UNKNOWN is how a constraint silently accepts the row it was written to refuse
-- -- the pattern 20261006095847_invitation_status.sql:131-133 and
-- 20261008115900_usage_counts.sql:169-171 both name. With the null branch
-- written, a null reason passes deliberately rather than by accident.
--
-- 500 is a new number and is chosen for what the field is for. docs/plan.md:
-- "Keep it short and factual: it is a note to the owner, not a case file about a
-- person." A bound is also a privacy control here and not only hygiene -- the
-- shorter the field, the less of somebody's story can be written into a column
-- nobody can read back through the app.
do $$
declare
  l_bad integer;
begin
  select count(*) into l_bad
  from public.account_status
  where reason is not null
    and char_length(reason) > 500;

  if l_bad > 0 then
    raise exception
      'Cannot add account_status_reason_length: % row(s) already hold a longer reason. Look at them in the dashboard, by hand -- this message names no row on purpose.',
      l_bad;
  end if;
end;
$$;

alter table public.account_status
  add constraint account_status_reason_length
  check (reason is null or char_length(reason) <= 500);

comment on constraint account_status_reason_length on public.account_status is
  'At most 500 characters, and null is allowed. Free text the owner types in the dashboard, which is the one write path in this app that no code checks. docs/plan.md asks for it to be "short and factual: it is a note to the owner, not a case file about a person".';

-- 3.3 and 3.4 Control characters in the two things people type.
--
-- A task title or a nickname may contain a newline, a tab or an escape today,
-- and a screen then draws something other than what the row holds. Nothing has
-- ever stopped one.
--
-- WHAT [[:cntrl:]] ACTUALLY REFUSES, measured on PostgreSQL 17.10 with encoding
-- UTF8 rather than taken from a manual page. evidence/build-it-25-task-cap.md
-- has the table:
--
--   REFUSED   U+0009 tab, U+000A line feed, U+000D carriage return,
--             U+001B escape, U+001F unit separator, U+007F delete,
--             AND THE WHOLE C1 RANGE: U+0080, U+0085, U+009F
--
--   ALLOWED   U+00A0 no-break space, U+200B zero-width space,
--             U+200E left-to-right mark, U+202E right-to-left override,
--             U+2028 line separator, U+FEFF zero-width no-break space, emoji
--
-- WHY THIS SPELLING AND NOT '[\x00-\x1F\x7F]', which was the proposal: both
-- compile and both work, and the hex range MISSES THE C1 RANGE. The two differ by
-- exactly U+0080-U+009F, so this one is strictly wider. That is a measurement,
-- not a preference.
--
-- AND U+0000 IS NOT IN EITHER LIST, because it cannot be in a text value at all:
-- PostgreSQL answers `ERROR: null character not permitted`. A comment claiming
-- this constraint refuses NUL would be a claim about something unreachable.
--
-- WHAT IT DOES NOT CATCH, AND THAT IS A KNOWN GAP RATHER THAN AN OVERSIGHT.
-- U+200B, U+202E, U+2028 and U+FEFF all get through, and U+2028 is a real line
-- break a screen will render as one. Widening to them would mean naming
-- codepoints rather than using a class, and it would refuse text somebody may
-- legitimately have pasted. It is its own issue rather than a wider constraint
-- here.
--
-- AND THIS ONE HAS A REAL COST, which is why it is the likeliest of the four to
-- be argued with: it refuses a paste that works today. Somebody copying two lines
-- out of a document into the task box is refused where they used to get one task
-- with a newline in it. docs/rate-limits.md said so when it proposed it -- "it
-- would refuse a paste that works today, so it is the proposal most likely to be
-- declined, and that is a reasonable thing to decline" -- and the owner took it
-- anyway on 2026-10-12. The app's own sentence for it is the next pull request's.
do $$
declare
  l_bad integer;
begin
  select count(*) into l_bad
  from public.tasks
  where title ~ '[[:cntrl:]]';

  if l_bad > 0 then
    raise exception
      'Cannot add tasks_title_no_control_chars: % row(s) already hold a control character. Look at them in the dashboard, by hand -- this message names no row on purpose.',
      l_bad;
  end if;
end;
$$;

alter table public.tasks
  add constraint tasks_title_no_control_chars
  check (title !~ '[[:cntrl:]]');

comment on constraint tasks_title_no_control_chars on public.tasks is
  'No control character in a task title. [[:cntrl:]] on a UTF-8 database refuses tab, line feed, carriage return, the rest of the C0 range, U+007F, and the C1 range U+0080-U+009F -- measured on PostgreSQL 17.10, not read off a manual. It does NOT refuse U+200B, U+202E, U+2028 or U+FEFF, which is a known gap with its own issue. U+0000 cannot be in a text value at all. Joins tasks_title_not_blank and tasks_title_length.';

do $$
declare
  l_bad integer;
begin
  select count(*) into l_bad
  from public.profiles
  where display_name ~ '[[:cntrl:]]';

  if l_bad > 0 then
    raise exception
      'Cannot add profiles_display_name_no_control_chars: % row(s) already hold a control character. Look at them in the dashboard, by hand -- this message names no row on purpose.',
      l_bad;
  end if;
end;
$$;

alter table public.profiles
  add constraint profiles_display_name_no_control_chars
  check (display_name !~ '[[:cntrl:]]');

comment on constraint profiles_display_name_no_control_chars on public.profiles is
  'No control character in a nickname. The same class and the same measured behaviour as tasks_title_no_control_chars. Less likely to bite than that one, because a nickname is typed rather than pasted. Joins profiles_display_name_not_blank and profiles_display_name_length.';

-- ---------------------------------------------------------------------------
-- 4. What the person sees, decided here and built in the NEXT pull request
-- ---------------------------------------------------------------------------
--
-- docs/plan.md leaves the wording open and fixes one thing about it: the screen
-- "says they have reached the most this app will hold and that deleting a task
-- makes room, rather than 'that did not save'. A refusal a person can act on
-- earns its own words."
--
-- THE PROBLEM, AND IT IS THE REASON THIS SECTION IS IN A MIGRATION. A policy
-- refusal is `42501`, "new row violates row-level security policy for table
-- tasks" -- measured, not guessed. That is ONE STATUS FOR EVERY WAY THIS POLICY
-- CAN REFUSE, and issue #174 is this repository's record of what goes wrong when
-- one status stands for more than one meaning.
--
-- THE OWNER'S DECISION OF 2026-10-12: THE SCREEN MUST NOT INFER THE CAP FROM A
-- BARE 42501. What it does instead, and it is why section 1 grants EXECUTE to
-- `authenticated`:
--
--   the action's insert is refused with 42501
--     -> it calls public.tasks_may_add()
--        -> false  the person is at the cap: the cap's own sentence, which says
--                  deleting a task makes room
--        -> true   something else refused it: the ordinary "could not add"
--                  sentence
--
-- So the screen ASKS rather than infers, and the two sentences cannot be swapped
-- by a change in which guard happens to fire first. The call is one bit about the
-- person themselves, it writes nothing, and it is made only after a refusal --
-- so the ordinary path costs nothing.
--
-- NOTHING OF THAT IS BUILT HERE. No action, no sentence and no screen is touched
-- by this file; this section is the design, written where the function it depends
-- on is defined, so the next pull request implements a decision rather than
-- making one.
--
-- ---------------------------------------------------------------------------
-- 5. What this migration does NOT do
-- ---------------------------------------------------------------------------
--
--   * IT IS NOT A RATE LIMIT. docs/plan.md: "It bounds how many a person holds,
--     not how fast they ask. A loop refused 10,000 times at the ceiling still
--     costs 10,000 requests, and nothing in this app bounds that." Unchanged by
--     this file.
--   * IT IS NOT PER TEAM. A team task belongs to the person who created it, so it
--     counts against theirs. Three people in a team have 1,500 between them.
--   * IT DOES NOT BOUND UPLOADS. Decision B is part 2b.
--   * AND IT PROMISES NOTHING ABOUT THE CONTENTS of a title or a nickname beyond
--     the three things the constraints say. A name made entirely of right-to-left
--     overrides still passes, which is the gap section 3 names.
