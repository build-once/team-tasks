-- Kill switches: feature_switches, the one function that reads them, and the two
-- restrictive storage policies that make the attachments switch real.
--
-- Build it 29, Lesson J24. "the kill switches are: AI suggestions, invitations,
-- attachments and payments. Store them in a feature_switches table that only the
-- database owner can change, read by each server function and by the storage
-- rules."
--
-- WHAT A KILL SWITCH IS FOR, in one sentence, because it decides every choice
-- below: on a bad day the owner must be able to stop one risky feature WITHOUT A
-- DEPLOY -- no branch, no pull request, no build, no waiting for Vercel -- by
-- changing one value in the Supabase Table Editor. docs/incident-plan.md is the
-- page that says how; this file is the half that makes it true.
--
-- EXPAND ONLY, with one exception that is additive too. One new table, one new
-- trigger, one new function, four seeded rows, and TWO NEW RESTRICTIVE POLICIES
-- on storage.objects. No existing table, column, constraint, index, policy,
-- trigger, function or grant is altered or dropped -- and that is the reason the
-- attachments switch is enforced by restrictive policies rather than by editing
-- the three policies 20261008191804_attachments_bucket.sql created: a restrictive
-- policy can only ever SUBTRACT, so adding one cannot widen what those three
-- allow, and their long expressions are not retyped here where a copy could drift.
--
-- DO NOT EDIT THIS FILE once it has been applied anywhere. A migration is applied
-- once; editing an applied one leaves the repository and every database that has
-- already run it silently disagreeing, and the edit reaches none of them. To
-- change any of this, add a new migration.
--
-- Where this migration has been applied is recorded in docs/environments.md and
-- evidence/, not here -- a status note kept in this file goes stale without anyone
-- noticing. On the day it was written it had been applied NOWHERE: not local, not
-- staging, not production.
--
-- ---------------------------------------------------------------------------
-- THE DIRECTION IT FAILS IN, WHICH IS THE ONE DECISION TO READ TWICE
-- ---------------------------------------------------------------------------
--
-- public.feature_on() answers true ONLY when there is a row saying so. No row,
-- an unknown feature word, a misspelling at a call site: all false, which means
-- SWITCHED OFF.
--
-- That is deliberately the opposite way round from "a new table starts out
-- harmless". A kill switch has exactly one failure that matters -- the owner
-- flips it off during an incident and the feature keeps running -- and every
-- other failure is cheap by comparison. Fail closed costs a quiet feature and a
-- sentence on a screen that says so; fail open costs the thing the switch was
-- flipped for.
--
-- SO THE FOUR ROWS ARE SEEDED IN THIS MIGRATION, in the same transaction as the
-- table, and there is no moment at which the table exists without them. A
-- database that has run this file has four rows, all on, and behaves exactly as it
-- did before.
--
-- AND DELETING A ROW SWITCHES THAT FEATURE OFF rather than back on. Said here
-- because it is surprising, and said in docs/incident-plan.md where somebody is
-- about to act: the way to use these is to change `enabled`, never to delete.
--
-- ---------------------------------------------------------------------------
-- WHO MAY CHANGE ONE: the database owner, in the dashboard, and nobody else
-- ---------------------------------------------------------------------------
--
-- No policy, and no table privilege for anon, authenticated or service_role --
-- the shape account_status and usage_counts already have. So:
--
--   * no signed-in person can read or write a switch through the Data API;
--   * NO SERVER FUNCTION CAN EITHER, even holding the service-role key. A
--     function that could switch a feature back on is a function that can undo
--     the owner's only lever on a bad day;
--   * the operator changes one in the Table Editor, which connects as the owner.
--
-- WHAT IS GRANTED IS EXECUTE ON ONE READ-ONLY FUNCTION, and that is unavoidable
-- rather than generous: the storage policies below are evaluated as the CALLER, so
-- `authenticated` must be able to run it, and the Edge Functions call it as
-- `service_role`. It returns one boolean about a feature of this app, takes no
-- user id, and reveals nothing about anybody -- and a signed-in person learns the
-- same fact from the screen a moment later, because the whole point is to tell
-- them the feature is off.

-- ---------------------------------------------------------------------------
-- 0. THERE IS NO PRE-CHECK, AND THERE WAS ONE UNTIL 2026-10-15
-- ---------------------------------------------------------------------------
--
-- This file opened with a `do` block that refused to go on unless the applying
-- role held ownership of storage.objects, in the shape
-- 20261012120000_upload_daily_count.sql asks about the TRIGGER privilege. IT WAS
-- WRONG, AND IT STOPPED A PUSH THAT WOULD HAVE WORKED: on staging
-- (`ghskxrhqlhvrhpnivqbd`, the owner's run of `supabase db push` on 15 October
-- 2026) it raised, naming `postgres` as the role without ownership --
--
--   Build it 29 creates two restrictive policies on storage.objects, which
--   needs ownership of that table, and the role applying it (postgres) does not
--   have it.  (SQLSTATE P0001)
--
-- -- and the same role created THREE policies on that same table on that same
-- project in October (20261008191804_attachments_bucket.sql, read back through
-- the staging connector: three policies, each `to authenticated`). So the check
-- said no to something that demonstrably works.
--
-- WHAT THE EXPRESSION WAS ACTUALLY TESTING, measured rather than guessed at
-- (evidence/build-it-29-kill-switches.md, "What CREATE POLICY requires"): a
-- table owned by another role, with two members of that role, gives
--
--   inheriting member      pg_has_role USAGE = t   create policy -> CREATE POLICY
--   NON-inheriting member  pg_has_role USAGE = f   create policy -> ERROR: must
--                                                  be owner of table objects
--
-- so `pg_has_role(..., 'USAGE')` does track what CREATE POLICY needs for an
-- ordinary member. It is not a nonsense test -- which is exactly why it is being
-- deleted rather than corrected: IT ASKED A REASONABLE QUESTION AND GOT AN ANSWER
-- THAT DOES NOT PREDICT THE OUTCOME ON SUPABASE, and nobody writing this knows
-- what does. Ownership is not a grantable privilege, so there is no
-- `has_table_privilege` equivalent to ask instead, and the next guess would be a
-- Supabase-internal role name this project has never read. **I do not know what
-- lets `postgres` create a policy on storage.objects on a Supabase project**; what
-- is known is that it did, twice, in October.
--
-- A PRE-CHECK THAT REFUSES A WORKING OPERATION IS WORSE THAN NO PRE-CHECK. It
-- turns a success into a blocked push, and it does it with a confident sentence.
--
-- ---------------------------------------------------------------------------
-- SO THE STATEMENT IS THE TEST, AND A FAILURE APPLIES NOTHING
-- ---------------------------------------------------------------------------
--
-- Which is what 20261008191804_attachments_bucket.sql already decided for the
-- same question, in its own words: whether the applying role "may insert into
-- storage.buckets and create policies on storage.objects" is "UNVERIFIED, and it
-- is the most likely way this file fails on staging: if it does, it fails LOUDLY,
-- on the first statement, having changed nothing."
--
-- AND "APPLIES NOTHING" IS CHECKED HERE RATHER THAN ASSUMED, because it is the
-- whole reason the pre-check can go. Read off the CLI's own source on 15 October
-- 2026 (`supabase/cli`, `apps/cli-go/pkg/migration/file.go`, `MigrationFile.ExecBatch`):
-- every statement of a migration is queued into one `pgconn.Batch` and sent as a
-- PIPELINE, with no `begin` and no `commit` anywhere in that path. PostgreSQL's
-- own documentation for that mode: "If the pipeline used an implicit transaction,
-- then operations that have already executed are rolled back and operations that
-- were queued to follow the failed operation are skipped entirely"
-- (https://www.postgresql.org/docs/17/libpq-pipeline-mode.html, read 2026-10-15).
--
-- SO ONE FILE IS ONE IMPLICIT TRANSACTION -- WITH ONE CAVEAT WORTH KNOWING. That
-- same function flushes the batch around six kinds of statement, each of which then
-- runs on its own: `create index`, `drop index`, `reindex`, `vacuum`,
-- `alter system` and `cluster`. A file containing one of those is applied in more
-- than one implicit transaction, and a later failure would leave the earlier part
-- committed. **This file contains none of the six**, and the migration's own
-- comment in section 1 says why it needs no index. If a later migration here ever
-- adds an index beside something that can be refused for a privilege, this
-- paragraph is the one to come back to.
--
-- WHAT THAT COSTS, stated rather than glossed: the failure message is now
-- PostgreSQL's rather than this file's -- `must be owner of table objects`, naming
-- the statement and its position -- instead of a sentence written here. That is a
-- worse message and a correct outcome, and the trade is the right way round.

-- ---------------------------------------------------------------------------
-- 1. feature_switches -- one row per switch
-- ---------------------------------------------------------------------------
--
-- THREE COLUMNS, AND IT HOLDS NOTHING ABOUT ANYBODY. No user id, no reason, no
-- history, no record of who flipped it. That is why this change adds no row to
-- docs/plan.md's appendix: there is no personal data here to describe. A row says
-- "this feature of this app is on or off, and when that last changed", and is
-- incapable of saying more.
--
-- NO HISTORY, on purpose and for the reason the suspension row gives for having
-- none: nothing in this version needs one, and a log of every time the owner
-- reached for a switch would be a new thing to keep and to protect. The run log
-- of an incident belongs in the issue the incident opens.
create table public.feature_switches (
  -- WHICH FEATURE. A short fixed word, never free text: the constraint below is
  -- the fixed list, and it is in the database rather than only in TypeScript so a
  -- typo cannot create a fifth switch that nothing watches.
  feature text not null primary key,

  -- ON OR OFF. not null, so the check in feature_on() has no third state to read
  -- -- a null here would be exactly the "unknown" this design refuses to guess at,
  -- and it is better refused by the column than interpreted by a function.
  enabled boolean not null default true,

  -- WHEN IT LAST CHANGED, stamped by the trigger below rather than by whoever is
  -- editing. It exists for one reason: on a bad day the question "is this switch
  -- the thing that changed just now?" is worth answering without guessing.
  changed_at timestamptz not null default now()
);

comment on table public.feature_switches is
  'One row per kill switch: whether a risky feature of this app is on, and when that last changed. Read through public.feature_on() by the five server functions and by two restrictive policies on storage.objects. No policy and no table privilege for any role, so nothing in the app -- not even a server function holding the service-role key -- can read or change a switch; the operator changes one in the dashboard, which is the whole point. Holds nothing about any person. A MISSING ROW MEANS OFF: see public.feature_on(). Four features, fixed by feature_switches_feature_allowed. See docs/incident-plan.md.';

comment on column public.feature_switches.feature is
  'Which feature: ai_suggestions, invitations, attachments or payments, and nothing else -- feature_switches_feature_allowed is the fixed list. Adding a switch needs a new migration, on purpose.';

comment on column public.feature_switches.enabled is
  'true when the feature works as usual. false switches it off: the server functions refuse with a friendly sentence and the storage rules stop new uploads and new links. Change THIS VALUE to use a switch; deleting the row also switches the feature off, which is the safe direction but is not how to do it.';

comment on column public.feature_switches.changed_at is
  'When enabled last changed, stamped by feature_switches_stamp_changed_at. Whatever a caller supplies is overwritten, so it cannot be wrong.';

-- THE FIXED LIST, and why these four. One per thing in this app that a bad day
-- might call for stopping, which is the owner's own list from Build it 29:
--
--   ai_suggestions  one metered request to Anthropic, from suggest-subtasks
--   invitations     one email to the email service, from invite-member -- and
--                   accepting one, from accept-invite, because the switch is
--                   about the feature rather than about one direction of it
--   attachments     files arriving from outside, and signed links going out
--   payments        money, from stripe-checkout and stripe-webhook
--
-- A check constraint rather than a Postgres enum, for the reason
-- 20261006095847_invitation_status.sql gives: every other restricted value in this
-- schema is a check constraint, and an enum's values cannot be removed later
-- without recreating the type.
--
-- The column is NOT NULL, so this check has no null to fall through: it never
-- evaluates to unknown, and "unknown" is how a check constraint silently accepts a
-- row it was written to refuse.
alter table public.feature_switches
  add constraint feature_switches_feature_allowed
  check (feature in ('ai_suggestions', 'invitations', 'attachments', 'payments'));

-- Without this line, the absence of policies below would mean nothing at all.
alter table public.feature_switches enable row level security;

-- AND NO POLICIES, on purpose, exactly as 20261004114313_suspend_accounts.sql
-- leaves account_status and 20261008115900_usage_counts.sql leaves usage_counts.
-- Row-level security refuses what no policy allows, so this is the whole of the
-- app's access to this table: none.
--
-- SUPABASE'S SECURITY ADVISOR REPORTS THIS AS `rls_enabled_no_policy`, and that is
-- the table working as designed rather than a finding to fix. evidence/production-log.md
-- records the same notice being accepted for account_status on 4 October 2026.

-- ---------------------------------------------------------------------------
-- 2. Who may reach the table: nobody
-- ---------------------------------------------------------------------------
--
-- Every grant and revoke written out, including the ones that are no-ops in one
-- direction or the other, for the reason 20261008115900_usage_counts.sql gives at
-- length: Supabase's old default granted select, insert, update and delete on every
-- public table to anon, authenticated and service_role, its new default (30 October
-- 2026) grants none, and this table must behave the same before and after that day.
revoke all on table public.feature_switches from public;
revoke all on table public.feature_switches from anon;
revoke all on table public.feature_switches from authenticated;

-- SERVICE_ROLE IS REVOKED WITH THE OTHER TWO AND NOTHING IS GIVEN BACK, and here
-- that is not a tidiness measure but the point of the table. account_status keeps
-- `select` for service_role because the server functions read it directly; this one
-- keeps nothing, because a server function that could write this table could switch
-- a feature back on -- and the owner's lever has to be a lever nothing else can
-- reach. The functions read it through feature_on(), which runs as its owner.
revoke all on table public.feature_switches from service_role;

-- ---------------------------------------------------------------------------
-- 3. changed_at is stamped, never supplied
-- ---------------------------------------------------------------------------
--
-- The same shape as profiles_stamp_ai_suggestions in
-- 20261007204900_ai_suggestions_consent.sql, with ONE DELIBERATE DIFFERENCE: that
-- trigger REFUSES a caller who supplies the timestamp, and this one overwrites it
-- instead.
--
-- Why the difference: the caller here is a person in the Supabase Table Editor,
-- which sends the whole row back when one checkbox changes. A trigger that refused
-- a supplied changed_at would refuse the only way this table is ever meant to be
-- used -- on the one day somebody is in a hurry. Overwriting is the behaviour that
-- makes the column true without standing in the way.
create function public.feature_switches_stamp_changed_at()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- Only when the switch itself moved. Editing nothing, or touching the row
  -- without changing `enabled`, leaves the timestamp alone -- so "when it last
  -- changed" means what it says rather than "when somebody last looked".
  if new.enabled is distinct from old.enabled then
    new.changed_at := now();
  else
    new.changed_at := old.changed_at;
  end if;
  return new;
end;
$$;

comment on function public.feature_switches_stamp_changed_at() is
  'Keeps feature_switches.changed_at honest: set to now() when enabled changes, left alone otherwise, and whatever a caller supplied is discarded either way.';

create trigger feature_switches_stamp_changed_at
  before update on public.feature_switches
  for each row
  execute function public.feature_switches_stamp_changed_at();

-- ---------------------------------------------------------------------------
-- 4. The four switches, all on
-- ---------------------------------------------------------------------------
--
-- IN THE SAME MIGRATION AS THE TABLE, because feature_on() reads a missing row as
-- OFF: a database that had the table and not the rows would be a database with
-- four features switched off and nothing to say why. These two statements are not
-- separable.
--
-- `on conflict do nothing` so that re-running this file against a database that
-- somehow already has a row does not overwrite the owner's setting with `true`.
-- Turning a feature back on is a decision, not a side effect of a migration.
insert into public.feature_switches (feature, enabled)
values
  ('ai_suggestions', true),
  ('invitations', true),
  ('attachments', true),
  ('payments', true)
on conflict (feature) do nothing;

-- ---------------------------------------------------------------------------
-- 5. feature_on() -- the only way to read a switch
-- ---------------------------------------------------------------------------
--
-- security definer, so it runs as the role that owns it rather than as the caller.
-- That is what lets the whole app read a switch while no role has a single
-- privilege on the table -- the same arrangement count_daily_use() uses, and for
-- the same reason.
--
-- The guards are 20261002122203_team_rules.sql's, unchanged:
--
--   set search_path = ''  so no schema is searched implicitly. A function running
--                         with more rights than its caller must not resolve a name
--                         through a path somebody else can change.
--   schema-qualified      the consequence: public.feature_switches must be written
--                         in full or it does not resolve at all.
--
-- `stable`, not volatile: it reads and never writes, and a stable function may be
-- evaluated once per statement rather than once per row -- which matters because a
-- storage policy below calls it while Postgres is deciding about a set of objects.
--
-- NO USER ID, AND NOTHING ABOUT WHO IS ASKING. A switch is a fact about this app,
-- not about a person, so there is nothing here that could be asked about somebody
-- else and nothing to leak. That is also why granting EXECUTE to `authenticated` is
-- a smaller thing than it looks: the answer is the same for everybody, and the app
-- is about to tell them anyway.
--
-- COALESCE TO false, WHICH IS THE WHOLE DESIGN AND IS ARGUED IN THE HEADER. No row
-- means off. An unknown feature word means off. A misspelling at a call site means
-- off, loudly and immediately, rather than a switch that silently does nothing.
create function public.feature_on(p_feature text)
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select coalesce(
    (
      select fs.enabled
      from public.feature_switches fs
      where fs.feature = p_feature
    ),
    false
  );
$$;

comment on function public.feature_on(text) is
  'Is this feature switched on? Reads public.feature_switches, which no role may touch directly. Returns false for a feature with no row and for an unknown word, so a missing switch and a typo both mean OFF -- the safe direction for a kill switch. Called by the five server functions as service_role and by two restrictive policies on storage.objects as the caller. Takes no user id and tells nothing about anybody. See docs/incident-plan.md.';

revoke execute on function public.feature_on(text) from public;
revoke execute on function public.feature_on(text) from anon;

-- authenticated, because the two restrictive policies below are evaluated as the
-- caller and a policy that cannot run its own function refuses everything.
grant execute on function public.feature_on(text) to authenticated;

-- service_role, because the five Edge Functions call it over PostgREST on an admin
-- connection. This is EXECUTE on a read, and it is the only thing about this table
-- a server function is given.
grant execute on function public.feature_on(text) to service_role;

-- ---------------------------------------------------------------------------
-- 6. The attachments switch, in the storage rules themselves
-- ---------------------------------------------------------------------------
--
-- AS RESTRICTIVE, which is what makes this safe to add to a table whose three
-- existing policies this change does not touch. Postgres ANDs every restrictive
-- policy with the OR of the permissive ones, so these two can only ever take access
-- away. There is no expression here that could widen anything, and the three
-- policies in 20261008191804_attachments_bucket.sql and the one in
-- 20261013140000_account_deletion.sql are left exactly as they are.
--
-- `bucket_id is distinct from 'attachments'` RATHER THAN `<> 'attachments'`, and
-- it matters: a restrictive policy whose expression is UNKNOWN refuses the row, so
-- a `<>` against a null bucket_id would quietly make objects outside this app's
-- bucket unreadable. `is distinct from` is true or false and never unknown.
--
-- TWO POLICIES AND NOT THREE: select and insert. No restrictive DELETE policy is
-- created -- and that buys LESS than it appears to, which is the one thing about
-- this section that was measured rather than reasoned.
--
-- WHAT WAS MEASURED, on a local PostgreSQL 17.10 sandbox with all eighteen
-- migrations applied (evidence/build-it-29-kill-switches.md, section 8c): with the
-- switch off, a signed-in person's
--
--   delete from storage.objects where bucket_id = 'attachments' and name = '...'
--
-- removes NOTHING -- `DELETE 0`, no error. The restrictive SELECT policy above is
-- why: the statement's own WHERE clause cannot see the row, so it matches none. A
-- delete is not refused; it quietly finds nothing to do.
--
-- SO "SWITCHED OFF" MEANS MORE THAN IT SAYS, and the plan is to say it rather than
-- to soften it: while attachments are off, nobody can attach a file, nobody gets a
-- new link, AND NOBODY CAN REMOVE A FILE EITHER -- which also means a task that has
-- files cannot be deleted, because tasks_refuse_delete_with_files refuses a task
-- while any object remains under attachments/<task id>/.
--
-- WHY THAT IS ACCEPTED rather than designed away:
--
--   * the person sees an honest sentence they can act on, not a crash. The app
--     deletes a task's files first and then the task; the refusal arrives as 23503,
--     which web/src/lib/tasks.ts already turns into "its files are still there";
--   * the alternative was to restrict INSERT only, which would leave every existing
--     file servable through a fresh signed link for as long as the switch was off --
--     and serving a file nobody read before it was stored is half of what this
--     switch is for;
--   * removing one unwanted file has always had an operator path. docs/plan.md:
--     "the operator in the dashboard is still the last resort". The dashboard
--     connects as the owner, and row-level security does not apply to it -- which
--     section 8e of the evidence shows for the service-role key.
--
-- docs/incident-plan.md carries this as a named consequence beside the switch, so
-- it is read by whoever is about to flip it rather than discovered afterwards.
--
-- A RESTRICTIVE POLICY IS NOT NEW TO THIS SCHEMA, which is worth knowing before
-- trusting the shape: "Suspended accounts are refused everything" on public.tasks
-- has been one since 20261004114313_suspend_accounts.sql.
--
-- WHAT IT DOES NOT REACH: a caller using the service-role key, which bypasses
-- row-level security altogether -- so a restore still works with the switch off,
-- which is the same hole section 5 of the attachments migration already documents
-- about its own policies. Nothing in this app uploads that way.
--
-- AND A LINK ALREADY HANDED OUT KEEPS WORKING for up to its five minutes. The check
-- happens when a signed URL is MADE, never when it is used -- docs/plan.md, "Links,
-- and what an unexpired one allows". A kill switch stops new links; it cannot
-- recall one, and nothing in this design can.
create policy "Attachments: no new link while the switch is off"
  on storage.objects
  as restrictive
  for select
  to authenticated
  using (
    bucket_id is distinct from 'attachments'
    or (select public.feature_on('attachments'))
  );

create policy "Attachments: no new file while the switch is off"
  on storage.objects
  as restrictive
  for insert
  to authenticated
  with check (
    bucket_id is distinct from 'attachments'
    or (select public.feature_on('attachments'))
  );

-- ---------------------------------------------------------------------------
-- How to read this back on a project, which is the only thing that proves it
-- ---------------------------------------------------------------------------
--
-- A green `db push` says the statements ran. It does not say what they left
-- behind. These are read-only and print no personal data:
--
--   select feature, enabled, changed_at from public.feature_switches order by feature;
--
--   select public.feature_on('ai_suggestions'), public.feature_on('nonsense');
--     -- expect true, false
--
--   select has_table_privilege('authenticated', 'public.feature_switches', 'select'),
--          has_table_privilege('service_role', 'public.feature_switches', 'select'),
--          has_table_privilege('service_role', 'public.feature_switches', 'update'),
--          has_function_privilege('authenticated', 'public.feature_on(text)', 'execute'),
--          has_function_privilege('service_role', 'public.feature_on(text)', 'execute');
--     -- expect false, false, false, true, true
--
--   select polname, polpermissive, polcmd
--   from pg_policy
--   where polrelid = 'storage.objects'::regclass
--   order by polname;
--     -- expect the two new rows with polpermissive = false, and the four existing
--     -- policies untouched with polpermissive = true
