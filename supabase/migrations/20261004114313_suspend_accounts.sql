-- The trigger on tasks is untouched, on purpose
-- ---------------------------------------------------------------------------
--
-- tasks_enforce_column_rules stays exactly as 20261002133637_tasks_join_teams.sql
-- created it. It is about which COLUMNS may differ after a change, which is a
-- different question from whether the person may act at all.
--
-- It does change which MESSAGE a suspended person sees in one case, and that is
-- worth writing down rather than discovering. A BEFORE ROW trigger runs before a
-- policy's `with check` is evaluated, so for an INSERT the trigger speaks first:
--
--   a suspended person adding a PERSONAL task          -> the trigger passes it,
--                                                         then with check
--                                                         refuses: "new row
--                                                         violates row-level
--                                                         security policy"
--   a suspended person adding a task to a team they
--   are NOT in                                         -> the trigger refuses
--                                                         first: "A task can
--                                                         only be added to a
--                                                         team its creator
--                                                         belongs to."
--
-- Both are refusals and nothing is written either way. For update, delete and
-- select the trigger never gets a say, because `using` matches no rows and so
-- there is no row for a BEFORE UPDATE trigger to fire on.

-- ---------------------------------------------------------------------------
-- What part B must do, and why this migration cannot
-- ---------------------------------------------------------------------------
--
-- THE FIVE RULES ABOVE DO NOT APPLY TO create-team, invite-member OR
-- accept-invite. All three use ctx.supabaseAdmin, which connects as
-- service_role, and service_role bypasses row-level security -- so a suspended
-- person can still create a team, still invite people to it, and still accept an
-- invitation, because the only checks on those paths are the ones written in
-- TypeScript, and none of them has heard of account_status.
--
-- That is not an oversight in this migration; it is the limit of what a database
-- rule can reach. Issue #128 says to list it and change nothing, so the full
-- list is in the pull request and summarised here:
--
--   create-team    after `const ownerId = ctx.userClaims?.id`, before the
--                  "at most 3 teams" count: refuse a caller with an
--                  account_status row.
--   invite-member  after `const callerId = ctx.userClaims?.id`, before the team
--                  lookup, and so before any email is decided or sent.
--   accept-invite  after the userId/userEmail checks and BEFORE the atomic claim
--                  -- the claim is one-shot, and claiming an invitation for
--                  somebody who is then refused burns it for good.
--
-- Each reads public.account_status with the admin client, which is what the
-- `grant select ... to service_role` above exists for, and each must fail CLOSED
-- on a read error: an unknown is not "not suspended". This project has made that
-- mistake's shape explicit before -- invite-member's own comments say "an unknown
-- is not a zero" about its two counts.
--
-- AND NONE OF THEM CALLS is_active(). It would not error, which is what makes it
-- dangerous: on an admin connection auth.uid() is null, so the answer is false
-- for everybody and all three functions would refuse every caller. See the
-- paragraph above the revokes in part 2.
